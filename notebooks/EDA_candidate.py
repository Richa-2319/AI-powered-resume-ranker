def print_profile(c, idx=None):
    p = c['profile']
    rs = c['redrob_signals']
    print('=' * 65)
    if idx is not None:
        print(f'  INDEX: {idx}')
    print(f'  ID:       {c["candidate_id"]}')
    print(f'  Name:     {p.get("anonymized_name")}')
    print(f'  Title:    {p.get("current_title")} @ {p.get("current_company")}')
    print(f'  Industry: {p.get("current_industry")}')
    print(f'  Location: {p.get("location")}, {p.get("country")}')
    print(f'  YOE:      {p.get("years_of_experience")} years')
    summary = (p.get('summary') or '')[:250]
    print(f'  Summary:  {summary}...' if len(p.get('summary', '')) > 250 else f'  Summary:  {summary}')
    print()
    print('  CAREER HISTORY:')
    for j in c.get('career_history', []):
        print(f'    - {j.get("title")} @ {j.get("company")} ({j.get("duration_months")}mo) [{j.get("industry")}]')
    print()
    print('  SKILLS (top 8 by duration):')
    sorted_skills = sorted(c.get('skills', []), key=lambda s: s.get('duration_months') or 0, reverse=True)[:8]
    for s in sorted_skills:
        print(f'    - {s["name"]:30s} {s.get("proficiency","?"):14s} {s.get("duration_months",0):3d}mo  {s.get("endorsements",0)} endorsements')
    print()
    print('  EDUCATION:')
    for e in c.get('education', []):
        print(f'    - {e.get("degree")} in {e.get("field_of_study")} @ {e.get("institution")} [{e.get("tier")}]')
    print()
    print('  SIGNALS:')
    print(f'    Open to work:        {rs.get("open_to_work_flag")}')
    print(f'    Last active:         {rs.get("last_active_date")}')
    print(f'    Response rate:       {rs.get("recruiter_response_rate")}')
    print(f'    GitHub score:        {rs.get("github_activity_score")}')
    print(f'    Notice period:       {rs.get("notice_period_days")} days')
    print(f'    Interview complete:  {rs.get("interview_completion_rate")}')
    print(f'    Offer acceptance:    {rs.get("offer_acceptance_rate")}')
    print(f'    Verified email/phone:{rs.get("verified_email")} / {rs.get("verified_phone")}')
    sal = rs.get('expected_salary_range_inr_lpa') or {}
    print(f'    Expected salary:     Rs.{sal.get("min")}-{sal.get("max")} LPA')
    print()


