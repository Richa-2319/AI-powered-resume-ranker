# Flag 1: Stated YOE vs summed career history
def yoe_vs_career(c):
    stated = c['profile'].get('years_of_experience') or 0
    summed = sum(j.get('duration_months') or 0 for j in c.get('career_history', [])) / 12
    if stated > 0 and summed > 0:
        return stated / summed
    return 1.0  # can't tell


df['yoe_vs_career_ratio'] = [yoe_vs_career(c) for c in candidates]

print("YOE-to-career-history ratio (>2.5 = suspicious):")
