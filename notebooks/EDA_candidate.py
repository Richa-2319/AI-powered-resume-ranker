def _days_since(date_str: str | None, ref: date | None = None) -> int:
    if not date_str:
        return 9999
    ref = ref or date.today()
    try:
        d = datetime.strptime(date_str[:10], "%Y-%m-%d").date()
        return (ref - d).days
    except Exception:
        return 9999

def _clamp(v: float, lo: float = 0.0, hi: float = 1.0) -> float:
    return max(lo, min(hi, v))

def _safe_signal(value, default: float = 0.0) -> float:
    """Return default if value is None, negative (sentinel -1), or missing."""
    if value is None or value < 0:
        return default
    return float(value)

# ─────────────────────────────────────────────
#  Honeypot detector
# ─────────────────────────────────────────────

def honeypot_penalty(candidate: dict[str, Any]) -> float:
    """
    Returns 0.0 for obvious fakes, 1.0 for clean profiles.
    EDA showed no honeypots in first 1000 — thresholds are kept but sensitivity tuned down.
    """
    profile = candidate.get("profile", {})
    career  = candidate.get("career_history", [])
    skills  = candidate.get("skills", [])
    signals = candidate.get("redrob_signals", {})
    flags   = 0

    # 1. Stated YOE much larger than summed career history
    stated_yoe    = profile.get("years_of_experience", 0) or 0
    summed_months = sum(r.get("duration_months", 0) or 0 for r in career)
    if stated_yoe > 0 and summed_months > 0:
        ratio = stated_yoe / max(summed_months / 12, 0.1)
        if ratio > 3.0:    # loosened from 2.5 — EDA showed 0 violations in 1000
            flags += 2

    # 2. "Expert" proficiency with 0 months duration
    # EDA: expert is extremely rare — any expert+0months is suspicious
    expert_zero = [s for s in skills
                   if s.get("proficiency") == "expert"
                   and (s.get("duration_months") or 0) == 0]
    if len(expert_zero) >= 2: flags += 2
    elif len(expert_zero) >= 1: flags += 1

    # 3. Implausible expert skill count
    # EDA: max was 5 expert skills in 1000 candidates — 6+ is suspicious
    expert_count = sum(1 for s in skills if s.get("proficiency") == "expert")
    if expert_count >= 6: flags += 2
    elif expert_count >= 4: flags += 1

    # 4. Open to work but inactive for a year
    if signals.get("open_to_work_flag") and _days_since(signals.get("last_active_date")) > 365:
        flags += 1

    # 5. Contradictory signals: 0% response rate but 100% offer acceptance
    # EDA: offer_acceptance -1 is "no data", not 0 — use _safe_signal
    rrr = signals.get("recruiter_response_rate", -1)
    oar = signals.get("offer_acceptance_rate", -1)
    if rrr == 0 and oar == 1.0:   # both must be real values
        flags += 2

    if flags >= 4: return 0.0
    if flags >= 3: return 0.15
    if flags >= 2: return 0.40
    if flags >= 1: return 0.75
    return 1.0

# ─────────────────────────────────────────────
#  Title score
# ─────────────────────────────────────────────

def title_score(candidate: dict[str, Any]) -> float:
    profile = candidate.get("profile", {})
    career  = candidate.get("career_history", [])

    all_titles = [profile.get("current_title", "")] + [j.get("title", "") for j in career]
    combined   = " ".join(all_titles)

    good_hits = len(GOOD_TITLES.findall(combined))
    bad_hits  = len(BAD_TITLES.findall(combined))

    # Current title weighted more heavily
    current = profile.get("current_title", "")
    if GOOD_TITLES.search(current): good_hits += 2
    if BAD_TITLES.search(current):  bad_hits  += 2

    return _clamp(good_hits * 0.25 - bad_hits * 0.30)

# ─────────────────────────────────────────────
#  Career score
# ─────────────────────────────────────────────

def career_score(candidate: dict[str, Any]) -> float:
    career = candidate.get("career_history", [])
    if not career:
        return 0.0

    total_months = ai_product_months = services_months = 0
    tenures = []

    for job in career:
        dur      = job.get("duration_months") or 0
        company  = job.get("company", "")
        industry = job.get("industry", "")
        title    = job.get("title", "")
        desc     = (job.get("description") or "").lower()

        total_months += dur
        tenures.append(dur)

        is_services    = bool(SERVICES_COMPANIES.search(company))
        is_good_title  = bool(GOOD_TITLES.search(title))
        is_tech_ind    = bool(TECH_INDUSTRY.search(industry))
        has_ai_content = any(kw in desc for kw in [
            "embedding", "retrieval", "ranking", "nlp", "machine learning",
            "vector", "search", "recommendation", "llm", "deep learning",
            "fine-tun", "transformer",
        ])

        if is_services:
            services_months += dur
        elif is_good_title or is_tech_ind or has_ai_content:
            ai_product_months += dur

    if total_months == 0:
        return 0.0

    ai_ratio       = ai_product_months / total_months
    services_ratio = services_months   / total_months

    # EDA: avg tenure median = 27.8 months, min = 10 months
    # Stability: <18 months avg = job-hopper; 30+ = stable
    avg_tenure = sum(tenures) / len(tenures) if tenures else 0
    stability  = _clamp((avg_tenure - 12) / 24)   # 12mo → 0, 36mo → 1

    return _clamp(
        ai_ratio       * 0.55 +
        (1 - services_ratio) * 0.25 +
        stability      * 0.20
    )

# ─────────────────────────────────────────────
#  Skill score
# ─────────────────────────────────────────────

def skill_score(candidate: dict[str, Any]) -> float:
    skills      = candidate.get("skills", [])
    signals     = candidate.get("redrob_signals", {})
    assessments = signals.get("skill_assessment_scores") or {}

    ai_score    = 0.0
    fluff_count = 0

    for s in skills:
        name_lower  = (s.get("name") or "").lower()
        proficiency = PROFICIENCY_WEIGHT.get(s.get("proficiency", "beginner"), 0.10)

        # EDA: avg skill duration = 17.3 months, max ~40
        # Duration multiplier: 0mo → 0.3, 24mo+ → 1.0
        dur_months = s.get("duration_months") or 0
        dur_mult   = _clamp(0.3 + dur_months / 28)

        # Endorsement multiplier: 0 → 1.0, 50+ → 1.4
        endorsements = min(s.get("endorsements") or 0, 50)
        end_mult     = 1.0 + (endorsements / 125)

        if any(core in name_lower for core in CORE_AI_SKILLS):
            # Bonus if there's a verified assessment score for this skill
            assess_bonus = 0.0
            for ak, av in assessments.items():
                if ak.lower() in name_lower or name_lower in ak.lower():
                    # assessment score 0-100 → 0 to 0.3 bonus
                    assess_bonus = min(_safe_signal(av, 0) / 333, 0.30)
                    break
            ai_score += proficiency * dur_mult * end_mult + assess_bonus

        # EDA confirmed: Content Writing, Agile, SAP, Six Sigma etc. are fluff in this context
        if any(fluff in name_lower for fluff in KEYWORD_FLUFF):
            fluff_count += 1

    # Normalise: expect ~8–10 strong AI skills for a great candidate
    normalised    = _clamp(ai_score / 10.0)
    fluff_penalty = _clamp(1.0 - fluff_count * 0.08)

    return normalised * fluff_penalty

# ─────────────────────────────────────────────
#  Experience score
# ─────────────────────────────────────────────

def experience_score(candidate: dict[str, Any]) -> float:
    """
    EDA: median YOE = 6.3, range 1.1–15.
    JD sweet spot: 5–9 years. <3 too junior, >12 over-qualified.
    """
    yoe = candidate.get("profile", {}).get("years_of_experience") or 0
    if yoe < 2:    return 0.10
    if yoe < 4:    return 0.35 + (yoe - 2) * 0.10   # 0.35 → 0.55
    if yoe <= 9:   return 0.60 + (yoe - 4) * 0.06   # 0.60 → 0.90
    if yoe <= 12:  return 0.88 - (yoe - 9) * 0.04   # 0.88 → 0.76
    return 0.70

# ─────────────────────────────────────────────
#  Location score
# ─────────────────────────────────────────────

def location_score(candidate: dict[str, Any]) -> float:
    """
    EDA: 75.9% are in India already — location is less of a differentiator than expected.
    Willing to relocate = 29.8%.
    """
    profile  = candidate.get("profile", {})
    signals  = candidate.get("redrob_signals", {})
    location = (profile.get("location") or "") + " " + (profile.get("country") or "")

    if PREFERRED_LOCATIONS.search(location):
        return 1.0
    if signals.get("willing_to_relocate"):
        return 0.60
    if "india" not in location.lower():
        return 0.25   # outside India, not willing to relocate
    return 0.50

# ─────────────────────────────────────────────
#  Education score
# ─────────────────────────────────────────────

def education_score(candidate: dict[str, Any]) -> float:
    edu = candidate.get("education", [])
    if not edu:
        return 0.30
    best = 0.0
    for e in edu:
        t = TIER_SCORE.get(e.get("tier", "unknown"), 0.35)
        f = 0.15 if CS_FIELDS.search(e.get("field_of_study") or "") else 0.0
        best = max(best, t + f)
    return _clamp(best)

# ─────────────────────────────────────────────
#  Availability multiplier
# ─────────────────────────────────────────────

def availability_multiplier(candidate: dict[str, Any]) -> float:
    """
    EDA key findings applied:
    - github_activity_score: -1 = not linked (neutral 0.5), not bad
    - offer_acceptance_rate: -1 = no data (skip it entirely)
    - notice_period: clusters at 30/60/90/120/150 — penalty starts at 90+ (median)
    - days_inactive: fairly uniform 21–261, median 128 days
    - open_to_work: only 34.6% True — strong differentiator, keep high weight
    """
    signals = candidate.get("redrob_signals", {})

    # Recency: median inactive = 128 days. 30d → 1.0, 200d → 0.2
    days_inactive = _days_since(signals.get("last_active_date"))
    recency = _clamp(1.0 - days_inactive / 200)

    # Open to work (34.6% True → strong differentiator)
    otw = 1.0 if signals.get("open_to_work_flag") else 0.45

    # Recruiter responsiveness (median ~0.4, fairly spread — useful signal)
    rrr = _safe_signal(signals.get("recruiter_response_rate"), default=0.3)

    # Interview reliability (median ~0.62, range 0.3–1.0)
    icr = _safe_signal(signals.get("interview_completion_rate"), default=0.5)

    # Notice period:
    # EDA clusters: 30=great, 60=fine, 90=median/ok, 120=penalty, 150=big penalty
    np_days = signals.get("notice_period_days") or 90
    if np_days <= 30:   notice = 1.00
    elif np_days <= 60: notice = 0.85
    elif np_days <= 90: notice = 0.65   # median — neutral
    elif np_days <= 120: notice = 0.40
    else:               notice = 0.20   # 150 days

    # GitHub score: EDA showed -1 = not linked (67% of candidates)
    # Treat -1 as neutral (0.5), not penalise. Only 3.9% have score > 50.
    gh_raw = signals.get("github_activity_score")
    if gh_raw is None or gh_raw < 0:
        github = 0.50    # neutral — no data, not a penalty
    else:
        github = _clamp(gh_raw / 100)

    # NOTE: offer_acceptance_rate intentionally excluded
    # EDA showed median = -1.0 (no data for most candidates)

    mult = (
        recency * 0.28 +
        otw     * 0.25 +
        rrr     * 0.20 +
        icr     * 0.15 +
        notice  * 0.07 +
        github  * 0.05
    )

    return _clamp(mult, 0.20, 1.0)

# ─────────────────────────────────────────────
#  Composite score
# ─────────────────────────────────────────────

def structured_score(candidate: dict[str, Any]) -> dict[str, float]:
    t  = title_score(candidate)
    c  = career_score(candidate)
    s  = skill_score(candidate)
    e  = experience_score(candidate)
    l  = location_score(candidate)
    ed = education_score(candidate)

    composite = (
        t  * WEIGHTS["title"]      +
        c  * WEIGHTS["career"]     +
        s  * WEIGHTS["skill"]      +
        e  * WEIGHTS["experience"] +
        l  * WEIGHTS["location"]   +
        ed * WEIGHTS["education"]
    )

    return {
        "title_score":      round(t,  4),
        "career_score":     round(c,  4),
        "skill_score":      round(s,  4),
        "experience_score": round(e,  4),
        "location_score":   round(l,  4),
        "education_score":  round(ed, 4),
        "structured":       round(composite, 4),
    }


def final_score(
    candidate: dict[str, Any],
    embedding_sim: float = 0.0,
    embed_weight:  float = 0.25,
) -> tuple[float, dict[str, float]]:
    """Returns (score_0_to_1, component_dict)."""
    components = structured_score(candidate)
    hp = honeypot_penalty(candidate)
    av = availability_multiplier(candidate)

    raw   = components["structured"] * (1 - embed_weight) + embedding_sim * embed_weight
    score = _clamp(raw * hp * av)

    components.update({
        "embedding_sim":     round(embedding_sim, 4),
        "honeypot_mult":     round(hp, 4),
        "availability_mult": round(av, 4),
        "final":             round(score, 4),
    })
    return score, components

# ─────────────────────────────────────────────
#  Text document builder (for embedding)
# ─────────────────────────────────────────────

def build_candidate_doc(candidate: dict[str, Any]) -> str:
    parts = []
    p = candidate.get("profile", {})

    parts.append(p.get("headline") or "")
    parts.append(p.get("summary") or "")
    parts.append(
        f"Current: {p.get('current_title','')} at "
        f"{p.get('current_company','')} ({p.get('current_industry','')})"
    )

    for job in (candidate.get("career_history") or [])[:5]:
        parts.append(
            f"{job.get('title','')} at {job.get('company','')} "
            f"({job.get('industry','')}): {job.get('description','')}"
        )

    # Only advanced/expert skills for the embedding doc
    top_skills = [
        s.get("name", "") for s in (candidate.get("skills") or [])
        if s.get("proficiency") in ("advanced", "expert")
    ]
    if top_skills:
        parts.append("Advanced skills: " + ", ".join(top_skills))

    for cert in (candidate.get("certifications") or []):
        parts.append(f"Cert: {cert.get('name','')} by {cert.get('issuer','')}")

    return " | ".join(pt for pt in parts if pt.strip())

# ─────────────────────────────────────────────
#  Reasoning generator
# ─────────────────────────────────────────────

def generate_reasoning(candidate: dict[str, Any], components: dict[str, float]) -> str:
    p       = candidate.get("profile", {})
    signals = candidate.get("redrob_signals", {})

    title   = p.get("current_title") or "Unknown role"
    company = p.get("current_company") or ""
    yoe     = p.get("years_of_experience") or 0
    loc     = p.get("location") or p.get("country") or "Unknown"

    # Top AI skills (advanced/expert only)
    skills    = candidate.get("skills", [])
    ai_skills = [
        s["name"] for s in skills
        if any(c in (s.get("name") or "").lower() for c in CORE_AI_SKILLS)
        and s.get("proficiency") in ("advanced", "expert")
    ]
    top_skills_str = ", ".join(ai_skills[:3]) if ai_skills else "no core AI skills"

    # Availability signals
    rrr    = _safe_signal(signals.get("recruiter_response_rate"), -1)
    gh     = signals.get("github_activity_score")
    np_d   = signals.get("notice_period_days") or 0
    otw    = signals.get("open_to_work_flag", False)

    # Warnings
    warnings = []
    if components.get("honeypot_mult", 1.0) < 0.5:
        warnings.append("profile inconsistencies flagged")
    if components.get("availability_mult", 1.0) < 0.35:
        warnings.append("low availability signals")
    if np_d >= 120:
        warnings.append(f"{np_d}-day notice period")

    # Sentence 1: core fit
    company_str = f" @ {company}" if company else ""
    s1 = f"{title}{company_str}, {yoe:.1f}y exp; AI skills: {top_skills_str}; {loc}."

    # Sentence 2: availability / caution
    extras = []
    if otw:
        extras.append("actively looking")
    if rrr >= 0:
        extras.append(f"response rate {rrr:.0%}")
    if gh is not None and gh > 0:
        extras.append(f"GitHub {gh:.0f}/100")
    if warnings:
        extras.append("Caution: " + "; ".join(warnings))

    s2 = ("; ".join(extras)).capitalize() + "." if extras else ""

    return (s1 + " " + s2).strip()