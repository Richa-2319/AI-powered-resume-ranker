# Overall honeypot summary
def count_honeypot_flags(c, df_row):
    flags = 0
    if df_row['yoe_vs_career_ratio'] > 2.5:
        flags += 2
    if df_row['n_expert_zero_duration'] >= 3:
        flags += 2
    elif df_row['n_expert_zero_duration'] >= 1:
        flags += 1
    if df_row['n_expert_skills'] >= 10:
        flags += 2
    elif df_row['n_expert_skills'] >= 7:
        flags += 1
    if df_row['open_to_work'] and df_row['days_inactive'] > 365:
        flags += 1
    if df_row['recruiter_response_rate'] == 0 and df_row['offer_acceptance_rate'] == 1.0:
        flags += 2
    return flags


df['honeypot_flags'] = [count_honeypot_flags(candidates[i], df.iloc[i]) for i in range(len(candidates))]

flag_dist = df['honeypot_flags'].value_counts().sort_index()
print("Honeypot flag distribution (0=clean, 4+=disqualify):")
